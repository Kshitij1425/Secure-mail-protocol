"""
Real mail server/client capture lab (controlled local test environment).

Servers:  Mailpit (Go, crypto/tls) - SMTP (STARTTLS / implicit TLS) and POP3S
          aiosmtpd (Python, OpenSSL) - legacy TLS 1.0 SMTP and plaintext SMTP
Clients:  Python standard library smtplib / poplib (OpenSSL)
Capture:  lab/recording_relay.py (application bytes + timing are real; TCP/IP headers reconstructed)

Everything listens on 127.0.0.1 only. Weak configurations exist only inside this lab.

Usage (from the repository root):
    python lab/real_mail_lab.py            # writes backend/tests/real_captures/*.pcap + manifest.json
"""
import json
import hashlib
import platform
import smtplib
import poplib
import socket
import ssl
import subprocess
import sys
import tempfile
import time
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from lab.pki import issue, lab_chain  # noqa: E402
from lab.recording_relay import RecordingRelay, write_pcap  # noqa: E402

MAILPIT = ROOT / "lab" / "tools" / "mailpit.exe"
OUT = ROOT / "backend" / "tests" / "real_captures"
HOST = socket.gethostname().encode()
# Mailpit greets with the OS hostname; replace it (same length) in plaintext bytes only.
SUBST = [(HOST, (b"mailpit-lab-host" * 8)[:len(HOST)])]
MSG = "From: alice@lab.test\r\nTo: bob@lab.test\r\nSubject: lab message\r\n\r\nTest message generated by the SecureMailScope lab.\r\n"


def free_port():
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    p = s.getsockname()[1]
    s.close()
    return p


def wait_port(port, timeout=15):
    end = time.time() + timeout
    while time.time() < end:
        try:
            socket.create_connection(("127.0.0.1", port), 0.3).close()
            return
        except OSError:
            time.sleep(0.1)
    raise RuntimeError(f"server on {port} did not start")


def client_ctx(max_v=None, min_v=None, ciphers=None):
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE  # lab certificates are not in any trust store
    if ciphers:
        ctx.set_ciphers(ciphers)
    if min_v:
        ctx.minimum_version = min_v
    if max_v:
        ctx.maximum_version = max_v
    return ctx


class Lab:
    def __init__(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="sms_lab_"))
        self.procs = []
        self.controllers = []

    def write(self, name, data: bytes) -> str:
        p = self.tmp / name
        p.write_bytes(data)
        return str(p)

    def mailpit(self, *, cert=None, chain=(), require_tls=False, pop3=False, auth_any=False):
        smtp, ui, pop = free_port(), free_port(), free_port()
        args = [str(MAILPIT), "--smtp", f"127.0.0.1:{smtp}", "--listen", f"127.0.0.1:{ui}",
                "--database", str(self.tmp / f"mp{smtp}.db"), "--quiet"]
        if cert:
            cp = self.write(f"c{smtp}.pem", cert.pem + b"".join(c.pem for c in chain))
            kp = self.write(f"k{smtp}.pem", cert.key_pem)
            args += ["--smtp-tls-cert", cp, "--smtp-tls-key", kp]
            if require_tls:
                args.append("--smtp-require-tls")
            if pop3:
                args += ["--pop3", f"127.0.0.1:{pop}", "--pop3-auth-file", self.write("pop.txt", b"alice:secret\n"),
                         "--pop3-tls-cert", cp, "--pop3-tls-key", kp]
        if auth_any:
            args += ["--smtp-auth-accept-any", "--smtp-auth-allow-insecure"]
        self.procs.append(subprocess.Popen(args, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL))
        wait_port(smtp)
        if pop3:
            wait_port(pop)
        return smtp, pop

    def aiosmtpd(self, *, tls_context=None, ident="lab-legacy ESMTP"):
        from aiosmtpd.controller import Controller
        from aiosmtpd.handlers import Sink
        port = free_port()
        c = Controller(Sink(), hostname="127.0.0.1", port=port, server_hostname="legacy.lab.test", ident=ident,
                       tls_context=tls_context, require_starttls=False)
        c.start()
        self.controllers.append(c)
        return port

    def close(self):
        for p in self.procs:
            p.terminate()
            p.wait(5)
        for c in self.controllers:
            c.stop()


@contextmanager
def relay(port, server_port, client_ip, server_ip):
    r = RecordingRelay(("127.0.0.1", port), server_port=server_port, client_ip=client_ip, server_ip=server_ip,
                       plaintext_substitutions=SUBST)
    try:
        yield r
    finally:
        time.sleep(0.2)
        r.close()


def smtp_starttls(port, ctx, send=True):
    s = smtplib.SMTP("127.0.0.1", port, local_hostname="client.lab.test", timeout=10)
    s.ehlo()
    s.starttls(context=ctx)
    s.ehlo()
    if send:
        s.sendmail("alice@lab.test", ["bob@lab.test"], MSG)
    s.quit()


def session(protocol, state, version, findings, certs=0, implicit=False, handshake="complete"):
    return {"protocol": protocol, "starttls_state": state, "tls_version": version, "findings": sorted(findings),
            "certificates": certs, "implicit_tls": implicit, "handshake_status": handshake}


def run():
    OUT.mkdir(parents=True, exist_ok=True)
    lab = Lab()
    captures = []

    def save(name, relays, condition, expected, servers, notes=""):
        path = OUT / f"{name}.pcap"
        frames = write_pcap(path, relays)
        captures.append({
            "name": name, "file": path.name, "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "frames": frames, "intended_condition": condition, "servers": servers,
            "client": f"Python {platform.python_version()} smtplib/poplib, {ssl.OPENSSL_VERSION}",
            "expected_sessions": expected, "notes": notes,
        })
        print(f"{name}: {frames} frames")

    try:
        # 1. Secure modern TLS: STARTTLS on 587, TLS 1.3 (certificate encrypted by the protocol)
        _, inter, leaf = lab_chain("mail.lab.test")
        p, _ = lab.mailpit(cert=leaf, chain=[inter])
        with relay(p, 587, "10.77.1.10", "10.77.0.25") as r:
            smtp_starttls(r.port, client_ctx())
        save("real_smtp_starttls_tls13", [r], "Secure modern TLS: SMTP submission with STARTTLS negotiating TLS 1.3",
             [session("SMTP", "TLS_ESTABLISHED", "TLSv1.3", [])], ["Mailpit v1.31.2"],
             "TLS 1.3 encrypts the server certificate; it must be reported as not observable.")

        # 2. SMTPS (implicit TLS, 465) with a CA-issued chain, client capped at TLS 1.2
        _, inter, leaf = lab_chain("smtps.lab.test")
        p, _ = lab.mailpit(cert=leaf, chain=[inter], require_tls=True)
        with relay(p, 465, "10.77.1.11", "10.77.0.26") as r:
            s = smtplib.SMTP_SSL("127.0.0.1", r.port, context=client_ctx(max_v=ssl.TLSVersion.TLSv1_2),
                                 local_hostname="client.lab.test", timeout=10)
            s.ehlo()
            s.sendmail("alice@lab.test", ["bob@lab.test"], MSG)
            s.quit()
        save("real_smtps_tls12_chain", [r], "Secure TLS 1.2 (ECDHE, AEAD) over implicit TLS with a leaf + intermediate chain",
             [session("SMTP", "TLS_ESTABLISHED", "TLSv1.2", [], certs=2, implicit=True)], ["Mailpit v1.31.2"])

        # 3. Certificate issue: expired self-signed certificate
        bad = issue("expired.lab.test", san=["expired.lab.test"], valid_from_days=-400, valid_to_days=-10)
        p, _ = lab.mailpit(cert=bad)
        with relay(p, 587, "10.77.1.12", "10.77.0.27") as r:
            smtp_starttls(r.port, client_ctx(max_v=ssl.TLSVersion.TLSv1_2))
        save("real_smtp_cert_expired_selfsigned", [r], "Certificate issue: self-signed certificate that expired 10 days before capture",
             [session("SMTP", "TLS_ESTABLISHED", "TLSv1.2", ["CERT-001", "CERT-005"], certs=1)], ["Mailpit v1.31.2"])

        # 4. Deprecated/weak TLS: TLS 1.0, static-RSA suite, 1024-bit RSA key (OpenSSL server via aiosmtpd)
        _, inter, weak = lab_chain("legacy.lab.test", key_bits=1024)
        sctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        sctx.minimum_version = sctx.maximum_version = ssl.TLSVersion.TLSv1
        sctx.set_ciphers("AES128-SHA:@SECLEVEL=0")
        sctx.load_cert_chain(lab.write("legacy.pem", weak.pem + inter.pem), lab.write("legacy.key", weak.key_pem))
        p = lab.aiosmtpd(tls_context=sctx)
        with relay(p, 25, "10.77.1.13", "10.77.0.28") as r:
            smtp_starttls(r.port, client_ctx(min_v=ssl.TLSVersion.TLSv1, max_v=ssl.TLSVersion.TLSv1,
                                             ciphers="AES128-SHA:@SECLEVEL=0"))
        save("real_smtp_tls10_legacy", [r], "Deprecated/weak TLS: TLS 1.0, TLS_RSA_WITH_AES_128_CBC_SHA (no forward secrecy), RSA-1024 leaf",
             [session("SMTP", "TLS_ESTABLISHED", "TLSv1.0", ["TLS-001", "TLS-004", "CERT-003"], certs=2)],
             ["aiosmtpd 1.4.6 (Python ssl / " + ssl.OPENSSL_VERSION + ")"])

        # 5. STARTTLS transition failure: client only offers TLS 1.0, modern server refuses (protocol_version alert)
        _, inter, leaf = lab_chain("mail.lab.test")
        p, _ = lab.mailpit(cert=leaf, chain=[inter])
        with relay(p, 587, "10.77.1.14", "10.77.0.29") as r:
            try:
                smtp_starttls(r.port, client_ctx(min_v=ssl.TLSVersion.TLSv1, max_v=ssl.TLSVersion.TLSv1,
                                                 ciphers="ALL:@SECLEVEL=0"), send=False)
            except ssl.SSLError:
                pass
        save("real_smtp_tls_handshake_refused", [r], "STARTTLS failure: legacy client (TLS 1.0 only) refused by the server; no TLS established",
             [session("SMTP", "TLS_FAILED", None, ["TLS-002", "TLS-006"], handshake="failed")], ["Mailpit v1.31.2"],
             "The legacy client cipher string 'ALL:@SECLEVEL=0' also offers anonymous (aNULL) suites, "
             "which is reported as TLS-006 (client offers insecure suites).")

        # 6. Insecure transition: server without TLS rejects STARTTLS; client authenticates and sends in plaintext
        p, _ = lab.mailpit(auth_any=True)
        with relay(p, 587, "10.77.1.15", "10.77.0.30") as r:
            s = smtplib.SMTP("127.0.0.1", r.port, local_hostname="client.lab.test", timeout=10)
            s.ehlo()
            code, _ = s.docmd("STARTTLS")
            s.login("alice", "lab-password-123")
            s.sendmail("alice@lab.test", ["bob@lab.test"], MSG)
            s.quit()
        save("real_smtp_starttls_rejected_plain_auth", [r],
             f"Insecure transition: STARTTLS rejected (server reply {code}); AUTH and message sent in plaintext",
             [session("SMTP", "STARTTLS_REJECTED", None, ["STLS-001", "PROTO-001", "PROTO-002"], handshake=None)],
             ["Mailpit v1.31.2"], "Credential values must not appear in any SecureMailScope output.")

        # 7. Mixed multi-protocol: SMTP STARTTLS, SMTPS, POP3S retrieval, plaintext SMTP
        _, inter, leaf = lab_chain("mail.lab.test")
        p_smtp, p_pop = lab.mailpit(cert=leaf, chain=[inter], pop3=True)
        _, inter2, leaf2 = lab_chain("smtps.lab.test")
        p_smtps, _ = lab.mailpit(cert=leaf2, chain=[inter2], require_tls=True)
        p_plain = lab.aiosmtpd(ident="relay.lab.test ESMTP")
        rs = []
        with relay(p_smtp, 587, "10.77.2.10", "10.77.0.25") as r1:
            smtp_starttls(r1.port, client_ctx(max_v=ssl.TLSVersion.TLSv1_2))
        with relay(p_smtps, 465, "10.77.2.11", "10.77.0.26") as r2:
            s = smtplib.SMTP_SSL("127.0.0.1", r2.port, context=client_ctx(), local_hostname="client.lab.test", timeout=10)
            s.sendmail("alice@lab.test", ["bob@lab.test"], MSG)
            s.quit()
        with relay(p_pop, 995, "10.77.2.12", "10.77.0.110") as r3:
            pp = poplib.POP3_SSL("127.0.0.1", r3.port, context=client_ctx(max_v=ssl.TLSVersion.TLSv1_2), timeout=10)
            pp.user("alice")
            pp.pass_("secret")
            pp.stat()
            pp.quit()
        with relay(p_plain, 25, "10.77.2.13", "10.77.0.31") as r4:
            s = smtplib.SMTP("127.0.0.1", r4.port, local_hostname="client.lab.test", timeout=10)
            s.ehlo()
            s.sendmail("alice@lab.test", ["bob@lab.test"], MSG)
            s.quit()
        rs = [r1, r2, r3, r4]
        save("real_mixed_multiprotocol", rs, "Mixed traffic: SMTP+STARTTLS (TLS 1.2), SMTPS (TLS 1.3), POP3S (TLS 1.2) and plaintext SMTP",
             [session("SMTP", "TLS_ESTABLISHED", "TLSv1.2", [], certs=2),
              session("SMTP", "TLS_ESTABLISHED", "TLSv1.3", [], implicit=True),
              session("POP3", "TLS_ESTABLISHED", "TLSv1.2", [], certs=2, implicit=True),
              session("SMTP", "PLAINTEXT", None, ["PROTO-001"], handshake=None)],
             ["Mailpit v1.31.2", "aiosmtpd 1.4.6"])
        # 8/9. Remediation pair on the SAME asset (10.77.0.50:587): legacy configuration, then remediated.
        old = issue("relay.lab.test", san=["relay.lab.test"], key_bits=1024, valid_from_days=-700, valid_to_days=-5)
        octx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        octx.minimum_version = octx.maximum_version = ssl.TLSVersion.TLSv1
        octx.set_ciphers("AES128-SHA:@SECLEVEL=0")
        octx.load_cert_chain(lab.write("old.pem", old.pem), lab.write("old.key", old.key_pem))
        p = lab.aiosmtpd(tls_context=octx, ident="relay.lab.test ESMTP")
        with relay(p, 587, "10.77.3.10", "10.77.0.50") as r:
            smtp_starttls(r.port, client_ctx(min_v=ssl.TLSVersion.TLSv1, max_v=ssl.TLSVersion.TLSv1,
                                             ciphers="AES128-SHA:@SECLEVEL=0"))
        save("real_remediation_before", [r], "Remediation study (before): relay.lab.test on 10.77.0.50:587 with TLS 1.0, "
             "static RSA and an expired self-signed RSA-1024 certificate",
             [session("SMTP", "TLS_ESTABLISHED", "TLSv1.0", ["TLS-001", "TLS-004", "CERT-001", "CERT-003", "CERT-005"],
                      certs=1)], ["aiosmtpd 1.4.6 (Python ssl / " + ssl.OPENSSL_VERSION + ")"],
             "Compare with real_remediation_after (same server address and port).")
        _, inter, new = lab_chain("relay.lab.test")
        p, _ = lab.mailpit(cert=new, chain=[inter])
        with relay(p, 587, "10.77.3.10", "10.77.0.50") as r:
            smtp_starttls(r.port, client_ctx(max_v=ssl.TLSVersion.TLSv1_2))
        save("real_remediation_after", [r], "Remediation study (after): same asset reconfigured with TLS 1.2+ "
             "(ECDHE, AEAD) and a new CA-issued RSA-2048 certificate chain",
             [session("SMTP", "TLS_ESTABLISHED", "TLSv1.2", [], certs=2)], ["Mailpit v1.31.2"],
             "Client capped at TLS 1.2 so that the new certificate is observable.")
    finally:
        lab.close()

    manifest = {
        "description": "Real email server/client captures generated in a controlled local test environment "
                       "(not real-world or enterprise traffic).",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generator": "lab/real_mail_lab.py",
        "capture_method": "lab/recording_relay.py: application-layer bytes (SMTP/POP3 dialogue and TLS records) and "
                          "their timing are exactly as exchanged by the real client and server; Ethernet/IPv4/TCP headers "
                          "are reconstructed (lab addresses 10.77.0.0/16, standard server ports). No raw packet capture "
                          "driver was available in the generating environment.",
        "plaintext_substitutions": "The lab host's name in Mailpit's plaintext greeting was replaced by a placeholder of "
                                   "equal length before TLS; no TLS bytes were modified.",
        "environment": {"os": platform.platform(), "python": platform.python_version(), "openssl": ssl.OPENSSL_VERSION},
        "not_covered_here": "IMAP / IMAPS (no IMAP server available without installation); see lab/docker for a "
                            "Postfix + Dovecot + tcpdump lab producing raw packet captures.",
        "captures": captures,
    }
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"manifest: {OUT / 'manifest.json'}")


if __name__ == "__main__":
    run()
