def main():
    parser = argparse.ArgumentParser(
        description="SecureMailScope M10 — CLI forensic report generation",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="Example: securemailscope analyze example.pcap --output-dir ./reports --json --html --pdf"
    )
    parser.add_argument("command", choices=["analyze"], help="Command: analyze a capture")
    parser.add_argument("capture", help="PCAP/PCAPNG file to analyze")
    parser.add_argument("--output-dir", default=".", help="Output directory for reports (default: current dir)")
    parser.add_argument("--json", action="store_true", help="Generate JSON report")
    parser.add_argument("--html", action="store_true", help="Generate HTML report")
    parser.add_argument("--pdf", action="store_true", help="Generate PDF report (from HTML)")
    parser.add_argument("--verbosity", choices=["quiet", "normal", "verbose"], default="normal")
    args = parser.parse_args()

    if not os.path.isfile(args.capture):
        print(f"ERROR: Capture file not found: {args.capture}", file=sys.stderr)
        sys.exit(2)

    # Compute capture hash
    capture_sha = compute_sha256(args.capture)

    # Run complete M1-M8 analysis + M9 scoring via the Orchestrator
    try:
        from securemailscope.core.orchestrator import Orchestrator
        orchestrator = Orchestrator(securemailscope_version=VERSION)
        posture, capture_metadata = orchestrator.analyze(args.capture)
    except Exception as e:
        print(f"ERROR: Analysis failed: {str(e)}", file=sys.stderr)
        if args.verbosity == "verbose":
            import traceback
            traceback.print_exc()
        sys.exit(1)

    # Build output directory
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    basename = Path(args.capture).stem
    reports_generated = []

    if args.json:
        jpath = out_dir / f"{basename}_report.json"
        report = build_json_report(posture, args.capture, capture_sha)
        with open(jpath, "w", encoding="utf-8") as f:
            json.dump(report, f, indent=2, default=str)
        reports_generated.append(str(jpath))
        if args.verbosity != "quiet":
            print(f"JSON report: {jpath}")

    if args.html:
        hpath = out_dir / f"{basename}_report.html"
        html_content = build_html_report(posture, args.capture, capture_sha)
        with open(hpath, "w", encoding="utf-8") as f:
            f.write(html_content)
        reports_generated.append(str(hpath))
        if args.verbosity != "quiet":
            print(f"HTML report: {hpath}")

    if args.pdf:
        # Use weasyprint if available; else skip with note
        try:
            import weasyprint
            pdf_path = out_dir / f"{basename}_report.pdf"
            html_path = out_dir / f"{basename}_report.html"
            if not html_path.exists():
                html_content = build_html_report(posture, args.capture, capture_sha)
                with open(html_path, "w", encoding="utf-8") as f:
                    f.write(html_content)
            weasyprint.HTML(str(html_path)).write_pdf(str(pdf_path))
            reports_generated.append(str(pdf_path))
            if args.verbosity != "quiet":
                print(f"PDF report: {pdf_path}")
        except ImportError:
            print("WARNING: weasyprint not installed; PDF skipped. Install with: pip install weasyprint", file=sys.stderr)

    # CLI summary (always printed unless quiet)
    if args.verbosity != "quiet":
        print()
        print("# SecureMailScope Analysis")
        print(f"Capture: {os.path.basename(args.capture)}")
        print(f"Packets: (see M1-M8 pipeline output)")
        print(f"Email sessions: {posture.total_sessions}")
        print(f"TLS sessions: {posture.tls_sessions}")
        print()
        print(f"Security Posture: {posture.overall_score:.0f}/100")
        print(f"Status: {posture.status.value}")
        print()
        print(f"Findings: {posture.findings_count}")
        # Severity counts from findings (simplified for CLI view)
        print()
        print("Top issues:")
        for i, c in enumerate(posture.top_contributors[:5], 1):
            print(f"{i}. {c.root_issue} ({c.severity}) — {c.affected_sessions} sessions")

    if args.json or args.html or args.pdf:
        sys.exit(0)
    else:
        # If no report format specified but analyze was called, print summary only
        sys.exit(0)


if __name__ == "__main__":
    main()
