VERSION = "0.1.0"


def compute_sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def build_json_report(posture: PostureScore, capture_path: str, capture_sha: str) -> dict:
    return {
        "report_version": "1.0",
        "tool": "SecureMailScope",
        "version": VERSION,
        "generated_at": posture.analyzed_at.isoformat(),
        "scoring_policy_version": posture.scoring_policy_version,
        "capture": {
            "filename": os.path.basename(capture_path),
            "path": capture_path,
            "sha256": capture_sha
        },
        "analysis_summary": posture.get_summary(),
        "posture_score": posture.to_dict(),
        "evidence_references": {
            "findings": posture.findings_count,
            "sessions_with_findings": posture.sessions_with_findings,
            "tls_coverage_percent": posture.tls_coverage_percent,
            "certificate_coverage_percent": posture.certificate_coverage_percent
        },
        "notes": [
            "Report generated by SecureMailScope M10.",
            "Evidence quality tracked per dimension (FULL / PARTIAL / INSUFFICIENT / NOT_OBSERVED).",
            "Missing evidence does not produce false security penalties."
        ]
    }


