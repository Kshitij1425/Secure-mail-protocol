"""
Validation layer 3: independently produced public mail captures (Wireshark wiki sample captures).

Not generated by SecureMailScope or its lab. Files are downloaded by
``python -m tests.external_captures.fetch`` (pinned SHA-256) and are not redistributed here;
the tests are skipped when the files are absent. See tests/external_captures/sources.json.
"""
import hashlib
import json
from pathlib import Path

import pytest

from securemailscope.core.orchestrator import Orchestrator

HERE = Path(__file__).parent / "external_captures"
SOURCES = json.loads((HERE / "sources.json").read_text(encoding="utf-8"))
CAPTURES = SOURCES["captures"]


def _path(cap) -> Path:
    p = HERE / "downloads" / cap["file"]
    if not p.exists():
        pytest.skip("external capture not downloaded (python -m tests.external_captures.fetch)")
    assert hashlib.sha256(p.read_bytes()).hexdigest() == cap["sha256"], "pinned SHA-256 mismatch"
    return p


def test_sources_record_provenance_and_licence():
    assert "not redistributed" in SOURCES["description"].lower() or "NOT redistributed" in SOURCES["description"]
    assert "GNU General Public License" in SOURCES["license"]
    for c in CAPTURES:
        assert c["url"].startswith("https://wiki.wireshark.org/") and len(c["sha256"]) == 64 and c["limitations"]


@pytest.mark.parametrize("cap", CAPTURES, ids=[c["file"] for c in CAPTURES])
def test_external_capture_observations(cap):
    result = Orchestrator().analyze(str(_path(cap)))
    (s,) = result.sessions
    e, t = cap["expected"], s.tls_data
    assert s.protocol.name == e["protocol"]
    assert s.stream.dst_port == e["server_port"] and s.implicit_tls is e["implicit_tls"]
    assert s.starttls_state.name == e["starttls_state"]
    assert (t.server_version if t else None) == e["tls_version"]
    assert (t.cipher_suite_name if t else None) == e["cipher_suite"]
    assert len(s.certificates) == e["certificates"]
    if e["self_signed"] is not None:
        assert s.certificates[0].is_self_signed is e["self_signed"]
    assert sorted({f.rule_id for f in s.findings}) == e["findings"]


@pytest.mark.parametrize("cap", [c for c in CAPTURES if c["expected"]["tls_version"]], ids=lambda c: c["file"])
def test_external_tls_parameters_agree_with_independent_parser(cap):
    """Negotiated version/cipher and offered RC4 suites, re-derived with dpkt.ssl (not SecureMailScope's parser)."""
    import dpkt
    from securemailscope.tls.ciphers import cipher_name
    server, offered = None, []
    with open(_path(cap), "rb") as fh:
        for _ts, buf in dpkt.pcapng.Reader(fh):
            tcp = dpkt.ethernet.Ethernet(buf).data.data
            if not isinstance(tcp, dpkt.tcp.TCP) or len(tcp.data) < 6 or tcp.data[0] != 0x16:
                continue
            try:
                records, _ = dpkt.ssl.tls_multi_factory(tcp.data)
            except Exception:  # noqa: BLE001 - non-handshake payloads are skipped
                continue
            for rec in records:
                try:
                    hs = dpkt.ssl.TLSHandshake(rec.data)
                except Exception:  # noqa: BLE001
                    continue
                if hs.type == 1:
                    offered = [cipher_name(c.code) for c in hs.data.ciphersuites]
                elif hs.type == 2:
                    server = (hs.data.version, cipher_name(hs.data.ciphersuite.code))
    assert server == (0x0303, cap["expected"]["cipher_suite"])  # TLS 1.2
    assert any("RC4" in n for n in offered)  # basis of TLS-006 (client offers insecure suites)
