import { useEffect, useState } from 'react';
import { useCapture } from '../context/CaptureContext';
import { getFindings, getFinding } from '../lib/api';
import type { FindingSummary, FindingDetail as FindingDetailType } from '../types/api';
import { SeverityBadge } from '../components/SeverityBadge';
import { Filter, Search, ArrowRight, X } from 'lucide-react';

export const FindingsPage = () => {
  const { activeCaptureId } = useCapture();
  const [findings, setFindings] = useState<FindingSummary[]>([]);
  const [selectedFinding, setSelectedFinding] = useState<FindingDetailType | null>(null);
  const [search, setSearch] = useState<string>('');
  const [severityFilter, setSeverityFilter] = useState<string>('all');

  useEffect(() => {
    let ignore = false;
    if (!activeCaptureId) {
      return;
    }

    const loadFindings = async () => {
      try {
        const data = await getFindings({ capture_id: activeCaptureId });
        if (!ignore) {
          setFindings(data);
          setSelectedFinding(null);
        }
      } catch (err) {
        if (!ignore) {
          console.error('Failed to load findings', err);
        }
      }
    };

    loadFindings();

    return () => {
      ignore = true;
    };
  }, [activeCaptureId]);

  const handleSelectFinding = async (id: string) => {
    try {
      const detail = await getFinding(id);
      setSelectedFinding(detail);
    } catch (e) {
      console.error(e);
    }
  };

  const currentFindings = activeCaptureId ? findings : [];
  const currentSelectedFinding = activeCaptureId ? selectedFinding : null;

  const filtered = currentFindings.filter(f => {
    const matchesSearch = f.title.toLowerCase().includes(search.toLowerCase()) || f.rule_id.toLowerCase().includes(search.toLowerCase());
    const matchesSeverity = severityFilter === 'all' || f.severity.toLowerCase() === severityFilter.toLowerCase();
    return matchesSearch && matchesSeverity;
  });

  return (
    <div className="space-y-6">
      <div>
        <h2 className="text-2xl font-bold text-slate-100 tracking-tight">Security Findings</h2>
        <p className="text-sm text-slate-400 mt-1">Deterministic policy findings generated by the M8 security rule engine.</p>
      </div>

      {/* Filter Bar */}
      <div className="flex flex-wrap items-center justify-between gap-4 bg-slate-900/40 p-4 rounded-lg border border-slate-800">
        <div className="flex items-center gap-3 flex-1 min-w-[240px]">
          <Search size={16} className="text-slate-500" />
          <input
            type="text"
            placeholder="Search findings by rule or title..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            className="bg-transparent text-sm text-slate-200 placeholder-slate-500 focus:outline-none w-full"
          />
        </div>

        <div className="flex items-center gap-3">
          <Filter size={16} className="text-slate-500" />
          <select
            value={severityFilter}
            onChange={(e) => setSeverityFilter(e.target.value)}
            className="bg-slate-950 border border-slate-700 text-slate-200 text-sm rounded px-3 py-1.5 focus:outline-none"
          >
            <option value="all">All Severities</option>
            <option value="critical">Critical</option>
            <option value="high">High</option>
            <option value="medium">Medium</option>
            <option value="low">Low</option>
          </select>
        </div>
      </div>

      {/* Main Container */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        {/* Table View */}
        <div className={`space-y-3 ${currentSelectedFinding ? 'lg:col-span-2' : 'lg:col-span-3'}`}>
          {filtered.length === 0 ? (
            <div className="text-center py-12 bg-slate-900/20 border border-slate-800 rounded-lg text-slate-500">
              No matching findings found.
            </div>
          ) : (
            filtered.map((f) => (
              <div
                key={f.finding_id}
                onClick={() => handleSelectFinding(f.finding_id)}
                className={`p-4 rounded-lg border transition-all cursor-pointer flex items-center justify-between ${
                  currentSelectedFinding?.finding_id === f.finding_id
                    ? 'bg-slate-800/80 border-amber-500/50'
                    : 'bg-slate-900/40 border-slate-800/80 hover:bg-slate-900/80 hover:border-slate-700'
                }`}
              >
                <div className="space-y-1">
                  <div className="flex items-center gap-2">
                    <SeverityBadge severity={f.severity} size="sm" />
                    <span className="text-xs font-mono text-slate-500">{f.rule_id}</span>
                  </div>
                  <h4 className="text-sm font-semibold text-slate-200">{f.title}</h4>
                </div>

                <div className="flex items-center gap-4">
                  <span className="text-xs text-slate-400 uppercase font-mono">{f.category}</span>
                  <ArrowRight size={16} className="text-slate-600" />
                </div>
              </div>
            ))
          )}
        </div>

        {/* Details Panel */}
        {currentSelectedFinding && (
          <div className="bg-slate-900/60 border border-slate-800 rounded-xl p-6 space-y-6 h-fit sticky top-6">
            <div className="flex items-start justify-between">
              <div className="space-y-1">
                <SeverityBadge severity={currentSelectedFinding.severity} />
                <h3 className="text-lg font-bold text-slate-100 mt-2">{currentSelectedFinding.title}</h3>
                <span className="text-xs font-mono text-slate-500">{currentSelectedFinding.rule_id}</span>
              </div>
              <button
                onClick={() => setSelectedFinding(null)}
                className="text-slate-500 hover:text-slate-300 p-1"
              >
                <X size={18} />
              </button>
            </div>

            <div className="space-y-4 text-sm divide-y divide-slate-800/60">
              <div className="pt-2">
                <span className="text-xs uppercase font-bold text-slate-400 block mb-1">Explanation</span>
                <p className="text-slate-300 leading-relaxed">{currentSelectedFinding.explanation || 'No detailed explanation provided.'}</p>
              </div>

              <div className="pt-4">
                <span className="text-xs uppercase font-bold text-slate-400 block mb-1">Evidence</span>
                <div className="bg-slate-950 p-3 rounded font-mono text-xs text-amber-300/90 border border-slate-800 overflow-x-auto">
                  {currentSelectedFinding.evidence || 'No direct evidence payload captured.'}
                </div>
              </div>

              <div className="pt-4">
                <span className="text-xs uppercase font-bold text-slate-400 block mb-1">Recommendation</span>
                <p className="text-emerald-400/90 font-medium leading-relaxed">{currentSelectedFinding.recommendation || 'Remediation advice unavailable.'}</p>
              </div>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};
